    // MARK: - ANIMATION RETRIEVAL
    public static func animation(for stage: EvolutionStage, frameIndex: Int) -> Frame {
        let isAlt = frameIndex % 2 == 1
        switch stage {
        // --- OVO 1 ---
        case .egg1:
            if frameIndex >= 3 {
                return eggCracked
            }
            return isAlt ? egg2 : egg1
        case .flapor:
            return isAlt ? flapor2 : flapor1
        case .pyrop:
            return isAlt ? pyrop2 : pyrop1
        case .tomaDrake:
            return isAlt ? tomaDrake2 : tomaDrake1
        case .tomaFlaris:
            return isAlt ? tomaFlaris2 : tomaFlaris1
        case .tomaIgnis:
            return isAlt ? tomaIgnis2 : tomaIgnis1
        case .tomaCoal:
            return isAlt ? tomaCoal2 : tomaCoal1

        // --- OVO 2 ---
        case .egg2:
            if frameIndex >= 3 {
                return eggCracked
            }
            return isAlt ? egg2_2 : egg2_1
        case .bubble:
            return isAlt ? bubble2 : bubble1
        case .drop:
            return isAlt ? drop2 : drop1
        case .aquapup:
            return isAlt ? aquapup2 : aquapup1
        case .finlet:
            return isAlt ? finlet2 : finlet1
        case .shelly:
            return isAlt ? shelly2 : shelly1
        case .jelly:
            return isAlt ? jelly2 : jelly1

        // --- OVO 3 ---
        case .egg3:
            if frameIndex >= 3 {
                return eggCracked
            }
            return isAlt ? egg3_2 : egg3_1
        case .seed:
            return isAlt ? seed2 : seed1
        case .leaf:
            return isAlt ? leaf2 : leaf1
        case .sprout:
            return isAlt ? sprout2 : sprout1
        case .thorn:
            return isAlt ? thorn2 : thorn1
        case .flutter:
            return isAlt ? flutter2 : flutter1
        case .twig:
            return isAlt ? twig2 : twig1

        // ADULTOS VACINA
        case .drakeLord, .solPhoenix, .ignisShaman, .coalTitan,
             .tsunamihound, .aquapegasus, .tortureshield, .hydromage,
             .woodtitan, .bloomdrake, .sylvanfly, .treemage:
            return isAlt ? adultVaccine2 : adultVaccine1
            
        // ADULTOS DADOS
        case .pyroBeast, .gryphFlame, .lavaRex, .sulfurHound,
             .wavecrest, .coralfin, .reefkraken, .mistwolf,
             .canopybeast, .cactusthorn, .junglehunter, .rootbeast:
            return isAlt ? adultData2 : adultData1
            
        // ADULTOS VÍRUS
        case .shadowDrake, .doomPhoenix, .venomCinder, .slagPile,
             .deepmaw, .abysssark, .toxicshell, .poisonjelly,
             .thornviper, .sporefungus, .waspvenom, .rotwight:
            return isAlt ? adultVirus2 : adultVirus1
            
        // PERFEITOS (Compartilham a mesma arte lendária do respectivo alinhamento)
        case .kaiserDrake, .kaiserBeast, .diabloDrake, .astroPhoenix, .gryphOverlord, .necroPhoenix, .ignisArchmage, .titanosaurus, .basiliskFlame, .omegaTitan, .cerberusSulfur, .plutoSlag,
             .neptunehound, .oceanking, .leviathan, .poseidonwing, .coralemperor, .krakenabyss, .aegistortoise, .abyssalkraken, .nukelist, .poseidonmage, .fenrirmist, .hadesjelly,
             .yggdrasiltitan, .forestguardian, .basiliskwood, .quetzalcoatl, .megacactus, .toxicspore, .monarchfly, .pantherjungle, .hornetempress, .druidarchmage, .gaiaelemental, .necrorot:
            return isAlt ? perfect2 : perfect1
        }
    }
